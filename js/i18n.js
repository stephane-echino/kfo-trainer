export function setLang(l) {
  lang = STR[l] ? l : 'en';
}

export function getLang() {
  return lang;
}

export function t(key, ...args) {
  const v = STR[lang][key] ?? STR.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
